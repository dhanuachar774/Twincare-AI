"""TwinCare AI - Synthetic Telemetry Simulation Engine.

Generates physiologically plausible time-series telemetry data for the virtual
patient. Employs circadian rhythm oscillation models, sleep cycles, meal-induced
glycemic curves, activity bursts, and stochastic sensor noise.

NOTE: All data generated by this module is 100% synthetic for academic demonstrations.
"""

from datetime import datetime, timedelta
from typing import Dict, Any, Optional
import numpy as np
import pandas as pd
from config import ACTIVITY_LEVEL_MAP


class SyntheticTelemetrySimulator:
    """Simulator that models virtual physiological telemetry over time."""

    def __init__(self, profile: Dict[str, Any], random_seed: Optional[int] = 42):
        """Initialize simulator with a virtual patient profile."""
        self.profile = profile
        self.rng = np.random.default_rng(seed=random_seed)

    def generate_timeline(
        self,
        duration_hours: int = 24,
        interval_minutes: int = 30,
        inject_anomaly: bool = False,
        anomaly_type: str = "Tachycardia Spike",
    ) -> pd.DataFrame:
        """Generate continuous synthetic telemetry dataframe.

        Parameters:
            duration_hours: Horizon length in hours (e.g. 24, 48, 168).
            interval_minutes: Telemetry reading resolution in minutes (e.g. 15, 30, 60).
            inject_anomaly: Whether to simulate an acute transient physiological anomaly.
            anomaly_type: The anomaly to inject ('Tachycardia Spike', 'Hypertensive Episode', 'Nocturnal Hypoxemia', 'Post-prandial Spike').

        Returns:
            pd.DataFrame: Timestamped dataframe containing all synthetic physiological traces.
        """
        num_points = int((duration_hours * 60) / interval_minutes)
        base_time = datetime.now().replace(minute=0, second=0, microsecond=0) - timedelta(hours=duration_hours)

        timestamps = [base_time + timedelta(minutes=i * interval_minutes) for i in range(num_points)]

        # Extract patient baseline parameters
        age = self.profile.get("age", 35)
        sleep_hours = self.profile.get("sleep_hours", 7.0)
        activity_level = self.profile.get("activity_level", "Moderate")
        stress_level = self.profile.get("stress_level", "Moderate")

        base_hr = float(self.profile.get("baseline_hr", 72))
        base_bp_sys = float(self.profile.get("baseline_bp_sys", 120))
        base_bp_dia = float(self.profile.get("baseline_bp_dia", 80))
        base_glucose = float(self.profile.get("baseline_glucose", 90))

        # Adjust baselines slightly for age and stress heuristics
        act_config = ACTIVITY_LEVEL_MAP.get(activity_level, ACTIVITY_LEVEL_MAP["Moderate"])
        stress_factor = 1.0
        if stress_level == "High":
            stress_factor = 1.15
            base_hr += 6.0
            base_bp_sys += 5.0
            base_glucose += 8.0
        elif stress_level == "Low":
            stress_factor = 0.90
            base_hr -= 3.0
            base_bp_sys -= 3.0

        if age > 55:
            # Vascular compliance heuristic: slight systolic increase with age
            base_bp_sys += (age - 55) * 0.35

        # Initialize telemetry arrays
        hr_series = []
        bp_sys_series = []
        bp_dia_series = []
        spo2_series = []
        glucose_series = []
        temp_series = []
        resp_series = []
        steps_series = []
        is_sleep_series = []
        stress_series = []

        # Sleep window definition: assume bedtime at 23:00 to (23:00 + sleep_hours)
        wake_hour = (23.0 + sleep_hours) % 24.0

        for t in timestamps:
            hour_float = t.hour + (t.minute / 60.0)

            # Determine whether current time is in the virtual sleep window
            if 23.0 <= hour_float or hour_float < wake_hour:
                is_sleep = True
            else:
                is_sleep = False
            is_sleep_series.append(is_sleep)

            # 1. Circadian Rhythm Harmonic (peaks around 16:00, nadir around 04:00)
            circadian_phase = 2.0 * np.pi * (hour_float - 16.0) / 24.0
            circadian_hr_effect = 6.0 * np.cos(circadian_phase)
            circadian_bp_effect = 5.0 * np.cos(circadian_phase)
            circadian_temp_effect = 0.6 * np.cos(circadian_phase)

            # 2. Activity / Exercise Simulation (daytime active intervals)
            is_exercise_time = False
            exercise_boost = 0.0
            step_count = 0

            if not is_sleep:
                # Moderate/athletic individuals have daytime workout windows (e.g. 07:30 or 18:00)
                if (7.0 <= hour_float <= 8.5) and activity_level in ["Moderate", "High (Athletic)"]:
                    is_exercise_time = True
                    exercise_boost = 25.0 if activity_level == "Moderate" else 42.0
                    step_count = int(self.rng.uniform(600, 1500) * act_config["step_multiplier"])
                elif (17.5 <= hour_float <= 19.0) and activity_level in ["High (Athletic)"]:
                    is_exercise_time = True
                    exercise_boost = 35.0
                    step_count = int(self.rng.uniform(800, 1800) * act_config["step_multiplier"])
                else:
                    # Regular daytime ambient activity
                    step_count = int(self.rng.uniform(20, 250) * act_config["step_multiplier"])
            else:
                step_count = int(self.rng.uniform(0, 5))

            steps_series.append(step_count)

            # 3. Heart Rate Calculation (BPM)
            # Nocturnal dipping: HR drops ~12-16% during sleep
            if is_sleep:
                sleep_dip = -0.14 * base_hr
                hr_noise = self.rng.normal(0, 1.8)
                current_hr = base_hr + sleep_dip + (circadian_hr_effect * 0.4) + hr_noise
            else:
                hr_noise = self.rng.normal(0, 2.5)
                current_hr = base_hr + circadian_hr_effect + exercise_boost + hr_noise

            hr_series.append(max(42.0, min(190.0, current_hr)))

            # 4. Blood Pressure Calculation (mmHg)
            # Systolic & Diastolic nocturnal dipping + activity elevation
            if is_sleep:
                bp_sys_dip = -12.0
                bp_dia_dip = -8.0
                sys_val = base_bp_sys + bp_sys_dip + self.rng.normal(0, 2.0)
                dia_val = base_bp_dia + bp_dia_dip + self.rng.normal(0, 1.5)
            else:
                exercise_sys_boost = exercise_boost * 0.45
                sys_val = base_bp_sys + circadian_bp_effect + exercise_sys_boost + self.rng.normal(0, 3.0)
                dia_val = base_bp_dia + (circadian_bp_effect * 0.5) + self.rng.normal(0, 2.0)

            bp_sys_series.append(max(75.0, min(210.0, sys_val)))
            bp_dia_series.append(max(50.0, min(130.0, dia_val)))

            # 5. Blood Oxygen Saturation (SpO2 %)
            # High precision baseline with occasional respiratory variance
            spo2_val = 98.2 - (0.5 if is_sleep else 0.0) + self.rng.normal(0, 0.4)
            # Ensure physiological saturation bounds
            spo2_series.append(max(85.0, min(100.0, spo2_val)))

            # 6. Blood Glucose Dynamics (mg/dL)
            # Modeled meal surges: Breakfast (08:00), Lunch (13:00), Dinner (19:30)
            glucose_peak = 0.0
            meal_windows = [(8.0, 32.0), (13.0, 38.0), (19.5, 42.0)]
            for meal_hour, peak_delta in meal_windows:
                delta_h = hour_float - meal_hour
                if 0.0 <= delta_h <= 3.5:
                    # Exponential rise and fall postprandial curve
                    surge = peak_delta * (delta_h / 1.0) * np.exp(1.0 - (delta_h / 1.0))
                    glucose_peak += max(0.0, surge)

            glucose_noise = self.rng.normal(0, 2.5)
            calc_glucose = base_glucose + glucose_peak + glucose_noise
            glucose_series.append(max(60.0, min(280.0, calc_glucose)))

            # 7. Body Temperature (°F)
            base_temp = 98.4
            calc_temp = base_temp + circadian_temp_effect + (0.4 if is_exercise_time else 0.0) + self.rng.normal(0, 0.15)
            temp_series.append(round(calc_temp, 2))

            # 8. Respiratory Rate (breaths/min)
            base_resp = 15.0
            calc_resp = base_resp + (6.0 if is_exercise_time else 0.0) - (2.0 if is_sleep else 0.0) + self.rng.normal(0, 0.8)
            resp_series.append(max(10.0, min(35.0, calc_resp)))

            # 9. Dynamic Stress Index (0-100)
            if is_sleep:
                calc_stress = 15.0 + self.rng.normal(0, 3.0)
            elif is_exercise_time:
                calc_stress = 65.0 + self.rng.normal(0, 5.0)
            else:
                calc_stress = (35.0 * stress_factor) + (10.0 * (current_hr / base_hr - 1.0)) + self.rng.normal(0, 4.0)
            stress_series.append(max(5.0, min(95.0, calc_stress)))

        df = pd.DataFrame({
            "timestamp": timestamps,
            "heart_rate": np.round(hr_series, 1),
            "blood_pressure_systolic": np.round(bp_sys_series, 1),
            "blood_pressure_diastolic": np.round(bp_dia_series, 1),
            "spo2": np.round(spo2_series, 1),
            "blood_glucose": np.round(glucose_series, 1),
            "temperature": np.round(temp_series, 2),
            "respiratory_rate": np.round(resp_series, 1),
            "activity_steps": steps_series,
            "stress_index": np.round(stress_series, 1),
            "is_sleep": is_sleep_series,
            "is_simulated": True,
        })

        # 10. Inject Scenario Anomaly if requested (useful for live hackathon presentation!)
        if inject_anomaly and len(df) > 10:
            target_idx = len(df) - 6  # ~3 hours prior to current moment
            if anomaly_type == "Tachycardia Spike":
                df.loc[target_idx:target_idx + 3, "heart_rate"] += 38.0
                df.loc[target_idx:target_idx + 3, "stress_index"] += 28.0
            elif anomaly_type == "Hypertensive Episode":
                df.loc[target_idx:target_idx + 3, "blood_pressure_systolic"] += 35.0
                df.loc[target_idx:target_idx + 3, "blood_pressure_diastolic"] += 18.0
            elif anomaly_type == "Nocturnal Hypoxemia":
                # Find recent sleep period
                sleep_indices = df[df["is_sleep"]].index
                if len(sleep_indices) > 2:
                    sub_idx = sleep_indices[-3:]
                    df.loc[sub_idx, "spo2"] -= 7.5
            elif anomaly_type == "Post-prandial Spike":
                df.loc[target_idx:target_idx + 3, "blood_glucose"] += 65.0

        return df
